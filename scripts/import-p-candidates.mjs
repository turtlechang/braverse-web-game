import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import {
  backfillVariantStats,
  getDatasetUrl,
  normalizeOfficialCard,
} from './import-official-cards.mjs'

export const P_CARD_PATTERN = /^P-\d{3}(?:@\d+)?$/i
export const DEFAULT_LOCALE = 'en'
export const DEFAULT_OUTPUT =
  'data/candidates/official-p-0xx-remaining.en.json'
export const DEFAULT_INVENTORY_OUTPUT = 'docs/p0xx-card-inventory.md'
const OFFICIAL_SITE_URL = 'https://cookierunbraverse.com'

const toOptionalString = (value) => {
  if (typeof value !== 'string') return null
  const trimmed = value.trim()
  return trimmed.length > 0 ? trimmed : null
}

const compareText = (left, right) => String(left).localeCompare(String(right), 'en')

export const selectP0xxRawCards = (rawCards, existingCardNumbers = []) => {
  if (!Array.isArray(rawCards)) {
    throw new Error('Official card data is missing the cardList array.')
  }

  const existing = new Set(existingCardNumbers)
  return rawCards.filter((card) => {
    const cardNumber = toOptionalString(card?.card_no)
    return Boolean(
      cardNumber && P_CARD_PATTERN.test(cardNumber) && !existing.has(cardNumber),
    )
  })
}

export const getDistinctBaseCardNumbers = (cards) =>
  [...new Set(cards.map((card) => card.baseCardNumber))].sort(compareText)

const countBy = (values) => {
  const counts = new Map()
  for (const value of values) {
    const label = value ?? 'UNSPECIFIED'
    counts.set(label, (counts.get(label) ?? 0) + 1)
  }
  return [...counts.entries()].sort(([left], [right]) => compareText(left, right))
}

const tableRows = (entries) =>
  entries.map(([label, count]) => `| ${label} | ${count} |`).join('\n')

const escapeCell = (value) =>
  String(value ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')

const getExistingCardNumbers = async (cardsDirectory) => {
  const files = (await readdir(cardsDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith('.json'))
    .map((entry) => entry.name)

  const existing = new Set()
  for (const file of files) {
    const parsed = JSON.parse(await readFile(resolve(cardsDirectory, file), 'utf8'))
    if (!Array.isArray(parsed.cards)) continue
    for (const card of parsed.cards) {
      if (typeof card?.cardNumber === 'string') existing.add(card.cardNumber)
    }
  }
  return existing
}

export const createP0xxCandidateDocument = ({
  rawCards,
  existingCardNumbers = [],
  locale = DEFAULT_LOCALE,
  sourceUrl = getDatasetUrl(locale),
  importedAt = new Date().toISOString(),
}) => {
  const matchingRawCards = selectP0xxRawCards(rawCards, existingCardNumbers)
  if (matchingRawCards.length === 0) {
    throw new Error('No unimported P-0XX cards were found in the official data.')
  }

  const cards = backfillVariantStats(
    matchingRawCards.map((card) => normalizeOfficialCard(card, sourceUrl)),
  )
  const existingCardCount = existingCardNumbers instanceof Set
    ? existingCardNumbers.size
    : existingCardNumbers.length

  return {
    schemaVersion: 1,
    source: {
      provider: 'CookieRun: Braverse official website',
      pageUrl: `${OFFICIAL_SITE_URL}/${locale}/cardList`,
      datasetUrl: sourceUrl,
      locale,
      fetchedAt: importedAt,
      totalAvailable: rawCards.length,
      matchedAvailable: rawCards.filter((card) => {
        const cardNumber = toOptionalString(card?.card_no)
        return Boolean(cardNumber && P_CARD_PATTERN.test(cardNumber))
      }).length,
      importedCount: cards.length,
      existingCardCount,
      filter: {
        categoryTitle: null,
        cardNumberPattern: P_CARD_PATTERN.source,
        excludeExisting: true,
      },
      candidateStatus: 'inventory',
      imagesDownloaded: false,
    },
    cards,
  }
}

export const createP0xxInventoryMarkdown = (document) => {
  const { cards, source } = document
  const baseCardNumbers = getDistinctBaseCardNumbers(cards)
  const variants = cards.filter((card) => card.variant !== null)
  const rows = cards
    .slice()
    .sort((left, right) => compareText(left.cardNumber, right.cardNumber))
    .map(
      (card) =>
        `| ${escapeCell(card.cardNumber)} | ${escapeCell(card.baseCardNumber)} | ${escapeCell(card.name)} | ${escapeCell(card.type)} | ${escapeCell(card.color)} | ${escapeCell(card.product?.title)} |`,
    )
    .join('\n')

  return [
    '# P-0XX Card Import Inventory',
    '',
    '> Generated by `npm run cards:import:p-candidate`. Candidates stay in `data/candidates/` until effect conversion and validation are complete.',
    '',
    '## Import scope',
    '',
    `- Official card list: [CookieRun: Braverse Card List](${source.pageUrl})`,
    `- Official JSON: \`${source.datasetUrl}\``,
    `- Fetched at: \`${source.fetchedAt}\``,
    `- Filter: \`${source.filter.cardNumberPattern}\``,
    '- P-0XX only; BSx@ and STx@ promotional reprints are excluded.',
    '',
    '## Counts',
    '',
    '| Item | Count |',
    '| --- | ---: |',
    `| Official records | ${source.totalAvailable} |`,
    `| Official P-0XX records | ${source.matchedAvailable} |`,
    `| Already in formal pool | ${source.existingCardCount} |`,
    `| Candidate records | ${cards.length} |`,
    `| Candidate base numbers | ${baseCardNumbers.length} |`,
    `| Candidate art variants | ${variants.length} |`,
    '',
    '## Type distribution',
    '',
    '| Type | Count |',
    '| --- | ---: |',
    tableRows(countBy(cards.map((card) => card.type))),
    '',
    '## Color distribution',
    '',
    '| Color | Count |',
    '| --- | ---: |',
    tableRows(countBy(cards.map((card) => card.color))),
    '',
    '## Cards',
    '',
    '| Number | Base number | Name | Type | Color | Product |',
    '| --- | --- | --- | --- | --- | --- |',
    rows,
    '',
    '## Audit checklist',
    '',
    '1. Change `inventory` to `promotion-ready` only after adapter conversion and semantic validation pass.',
    '2. Check every `test-state=card:P-XXX` route for prompts, payment, costs, targets, Then, FLIP, trap, and stage flows.',
    '3. Run `npm run promote:candidate` only after the candidate and browser audits pass.',
    '',
  ].join('\n')
}

export const runP0xxCandidateImport = async ({
  locale = DEFAULT_LOCALE,
  output = DEFAULT_OUTPUT,
  inventoryOutput = DEFAULT_INVENTORY_OUTPUT,
  cardsDirectory = 'data/cards',
  fetchImpl = fetch,
  importedAt,
} = {}) => {
  const sourceUrl = getDatasetUrl(locale)
  const response = await fetchImpl(sourceUrl, {
    headers: {
      accept: 'application/json',
      'user-agent': 'braverse-web-game-p-card-importer/0.1',
    },
  })
  if (!response.ok) {
    throw new Error(`Official card data request failed: HTTP ${response.status}`)
  }

  const payload = await response.json()
  const existingCardNumbers = await getExistingCardNumbers(resolve(cardsDirectory))
  const document = createP0xxCandidateDocument({
    rawCards: payload.cardList,
    existingCardNumbers,
    locale,
    sourceUrl,
    importedAt,
  })
  const inventory = createP0xxInventoryMarkdown(document)
  const outputPath = resolve(output)
  const inventoryPath = resolve(inventoryOutput)

  await mkdir(dirname(outputPath), { recursive: true })
  await mkdir(dirname(inventoryPath), { recursive: true })
  await writeFile(outputPath, `${JSON.stringify(document, null, 2)}\n`, 'utf8')
  await writeFile(inventoryPath, inventory, 'utf8')

  return { document, inventory, outputPath, inventoryPath }
}

const parseArguments = (argumentsList) => {
  const options = {
    locale: DEFAULT_LOCALE,
    output: DEFAULT_OUTPUT,
    inventoryOutput: DEFAULT_INVENTORY_OUTPUT,
    cardsDirectory: 'data/cards',
  }

  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index]
    const nextValue = argumentsList[index + 1]

    if (argument === '--locale' && nextValue) {
      options.locale = nextValue
      index += 1
    } else if (argument === '--output' && nextValue) {
      options.output = nextValue
      index += 1
    } else if (argument === '--inventory-output' && nextValue) {
      options.inventoryOutput = nextValue
      index += 1
    } else if (argument === '--cards-directory' && nextValue) {
      options.cardsDirectory = nextValue
      index += 1
    } else {
      throw new Error(`Unsupported argument: ${argument}`)
    }
  }

  getDatasetUrl(options.locale)
  return options
}

const isDirectExecution =
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href

if (isDirectExecution) {
  try {
    const { document, outputPath, inventoryPath } = await runP0xxCandidateImport(
      parseArguments(process.argv.slice(2)),
    )
    console.log(`Imported ${document.source.importedCount} P-0XX candidates: ${outputPath}`)
    console.log(`Generated inventory: ${inventoryPath}`)
    console.log('Candidate status is inventory; convert and validate effects before promote.')
  } catch (error) {
    console.error(error instanceof Error ? error.message : error)
    process.exitCode = 1
  }
}
